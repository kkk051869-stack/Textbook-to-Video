/**
 * ============================================
 * Slide Controller（教学动画控制器）
 * ============================================
 *
 * 功能：
 *   - 页面切换（键盘、滚轮、触摸）
 *   - CSS delay class 驱动的入场动画
 *   - data-step 分步揭示（按音频时长均分或精确时间轴）
 *   - slideTimelines 精确时间轴同步（trigger_at_sec）
 *   - slideTransitions 方向性页面转场
 *   - FLIP 布局动画（data-flip-id 元素在 step 切换时平滑移动）
 *   - SVG 描边动画（.svg-draw 元素跟随 .show 触发）
 *
 * HTML 结构要求：
 *   div.slide-container > div.slide.active + div.slide * N
 *
 * 动画元素标记：
 *   div.anim.anim-up.d2              — 入场动画 + CSS delay
 *   div.anim.anim-card.d3[data-step="1"]  — 分步揭示
 *   div.anim[data-anim-id="e2"]      — 时间轴精确控制
 *   div[data-flip-id="card1"]        — FLIP 布局动画
 *   path.svg-draw                    — SVG 描边动画
 *
 * 全局变量（由 pipeline 注入）：
 *   slideDurations: number[]      — 每页时长（毫秒）
 *   slideTimelines: array[]       — 每页时间轴 [{selector, at_ms}]
 *   slideTransitions: string[]    — 每页转场类型
 *
 * API:
 *   SlideController.go(index)
 *   SlideController.next()
 *   SlideController.prev()
 *   SlideController.current()
 *   SlideController.total()
 */

(function () {
    "use strict";

    var slides = document.querySelectorAll(".slide");
    var total = slides.length;
    var current = 0;
    var transitioning = false;
    var TRANSITION_DURATION = 500; // ms
    var DEFAULT_SLIDE_DURATION = 5000; // ms
    var DEFAULT_ANIMATION_DURATION = 600; // ms
    var pendingAnimationTimers = [];
    var animationStartedAt = 0;

    window.animationTrace = Array.isArray(window.animationTrace)
        ? window.animationTrace : [];

    var SUPPORTED_ACTIONS = {
        show: true,
        highlight: true,
        pulse: true,
        fadeOut: true,
        dim: true,
        focus: true,
        draw: true,
        grow: true,
        move: true,
    };

    var SUPPORTED_EFFECTS = {
        fadeIn: true,
        fadeInUp: true,
        fadeInLeft: true,
        fadeInRight: true,
        fadeInDown: true,
        bounceIn: true,
        zoomIn: true,
        slideInLeft: true,
        slideInRight: true,
        drawPath: true,
        growBar: true,
        pulse: true,
        highlight: true,
        fadeOut: true,
        legacy: true,
    };

    function clearAnimationTimers() {
        pendingAnimationTimers.forEach(function (record) {
            var timer = record && record.timer != null ? record.timer : record;
            clearTimeout(timer);
            if (record && record.cleanup) {
                record.cleanup();
                record.cleanup = null;
            }
            if (record && record.trace && record.trace.status === "scheduled") {
                finishTrace(record.trace, "cancelled", "Animation timer cancelled");
            }
        });
        pendingAnimationTimers = [];
    }

    function normalizeTimelineEntry(entry, index) {
        if (entry && entry.event_id) return entry;
        // Compatibility for HTML generated by the pre-v2 compiler.
        return {
            event_id: "legacy-a" + (index + 1),
            slide_id: "legacy",
            target: "",
            selector: entry && entry.selector,
            action: "show",
            effect: "legacy",
            start_ms: entry && entry.start_ms != null ? entry.start_ms : (entry && entry.at_ms) || 0,
            duration_ms: DEFAULT_ANIMATION_DURATION,
            easing: "ease-out",
        };
    }

    function scheduleTrace(event) {
        var trace = {
            event_id: event.event_id,
            slide_id: event.slide_id,
            target: event.target,
            action: event.action,
            effect: event.effect,
            planned_ms: Number(event.start_ms) || 0,
            duration_ms: eventDuration(event),
            easing: event.easing || "ease-out",
            actual_ms: null,
            status: "scheduled",
            error: null,
        };
        window.animationTrace.push(trace);
        return trace;
    }

    function finishTrace(trace, status, error) {
        if (!trace || trace.status !== "scheduled") return;
        trace.actual_ms = Math.round(performance.now() - animationStartedAt);
        trace.status = status;
        trace.error = error || null;
    }

    function eventDuration(event) {
        var duration = Number(event && event.duration_ms);
        return isFinite(duration) && duration >= 0
            ? duration : DEFAULT_ANIMATION_DURATION;
    }

    function completeAnimationRecord(record, status, error) {
        if (record && record.cleanup) {
            record.cleanup();
            record.cleanup = null;
        }
        finishTrace(record && record.trace, status, error);
    }

    function observeAnimationStart(trace, elements) {
        var targets = Array.prototype.slice.call(elements || []);
        var active = true;
        function cleanup() {
            if (!active) return;
            active = false;
            targets.forEach(function (element) {
                element.removeEventListener("animationstart", onStart);
            });
        }
        function onStart(event) {
            if (trace.status !== "scheduled" || targets.indexOf(event.target) < 0) return;
            cleanup();
            finishTrace(trace, "executed", null);
        }
        targets.forEach(function (element) {
            element.addEventListener("animationstart", onStart);
        });
        return cleanup;
    }

    function observeTransitionStart(trace, element) {
        var active = true;
        function cleanup() {
            if (!active) return;
            active = false;
            element.removeEventListener("transitionstart", onStart);
        }
        function onStart(event) {
            if (trace.status !== "scheduled"
                || event.target !== element || event.propertyName !== "transform") return;
            cleanup();
            finishTrace(trace, "executed", null);
        }
        element.addEventListener("transitionstart", onStart);
        return cleanup;
    }

    function eventNeedsAnimationStart(event) {
        var action = event && event.action;
        return eventDuration(event) > 0 && action !== "dim" && action !== "focus" && action !== "move";
    }

    function animationTargetsForEvent(element, event) {
        if (event.action === "draw" || event.effect === "drawPath") {
            var paths = [];
            if (element.classList.contains("svg-draw")) paths.push(element);
            element.querySelectorAll(".svg-draw").forEach(function (path) {
                paths.push(path);
            });
            return paths;
        }
        return [element];
    }

    function effectClasses(effect) {
        return {
            fadeIn: ["anim-card"],
            fadeInUp: ["anim-up"],
            fadeInLeft: ["anim-left"],
            fadeInRight: ["anim-right"],
            fadeInDown: ["anim-down"],
            bounceIn: ["anim-scale"],
            zoomIn: ["anim-scale"],
            slideInLeft: ["anim-left"],
            slideInRight: ["anim-right"],
        }[effect] || [];
    }

    function applyEvent(element, event, slide) {
        var action = event.action || "show";
        var effect = event.effect || "fadeInUp";
        if (!SUPPORTED_ACTIONS[action]) return { ok: false, error: "unsupported_action:" + action };
        if (!SUPPORTED_EFFECTS[effect]) return { ok: false, error: "unsupported_effect:" + effect };

        if (action === "move") {
            var targetStep = parseInt(element.dataset.step || "", 10);
            if (effect !== "legacy") {
                return { ok: false, error: "unsupported_move:effect=" + effect };
            }
            if (!slide || !element.dataset.flipId || !isFinite(targetStep) || targetStep < 0) {
                return { ok: false, error: "unsupported_move:requires data-flip-id and data-step" };
            }
            var flipMatches = [];
            slide.querySelectorAll("[data-flip-id]").forEach(function (candidate) {
                if (candidate.dataset.flipId === element.dataset.flipId) flipMatches.push(candidate);
            });
            if (flipMatches.length !== 1 || flipMatches[0] !== element) {
                return { ok: false, error: "unsupported_move:data-flip-id must identify one element" };
            }
            var moveDuration = eventDuration(event);
            var moveEasing = event.easing || "ease-out";
            var wasShown = element.classList.contains("show");
            element.classList.add("event-move");
            element.style.setProperty("--flip-duration", (moveDuration / 1000) + "s");
            element.style.setProperty("--flip-easing", moveEasing);
            var moved = showStepWithFlip(
                slide, targetStep, true, moveDuration, moveEasing, element.dataset.flipId
            );
            if (!moved) {
                element.classList.remove("event-move");
                if (!wasShown) element.classList.remove("show");
                element.style.removeProperty("--flip-duration");
                element.style.removeProperty("--flip-easing");
                return { ok: false, error: "unsupported_move:no position change" };
            }
            return { ok: true, waitForTransitionStart: moveDuration > 0 };
        }

        var duration = eventDuration(event);
        var drawTargets = null;
        if (action === "draw" || effect === "drawPath") {
            drawTargets = [];
            if (element.classList.contains("svg-draw")) drawTargets.push(element);
            element.querySelectorAll(".svg-draw").forEach(function (path) {
                drawTargets.push(path);
            });
            if (!drawTargets.length) {
                return { ok: false, error: "unsupported_effect:draw_requires_svg" };
            }
        }
        element.classList.add("event-timed");
        element.style.setProperty("--anim-event-duration", (duration / 1000) + "s");
        element.style.setProperty("--anim-event-easing", event.easing || "ease-out");
        effectClasses(effect).forEach(function (name) { element.classList.add(name); });

        if (action === "show") element.classList.add("show");
        if (action === "focus") {
            element.classList.add("show", "event-focus");
        } else if (action === "highlight" || effect === "highlight") {
            element.classList.add("show", "event-highlight");
        } else if (action === "pulse" || effect === "pulse") {
            element.classList.add("show", "event-pulse");
        } else if (action === "fadeOut" || effect === "fadeOut") {
            element.classList.add("event-fade-out");
        } else if (action === "dim") {
            element.classList.add("show", "event-dim");
        } else if (action === "draw" || effect === "drawPath") {
            element.classList.add("show");
            drawTargets.forEach(function (path) {
                path.classList.add("active-draw");
            });
        } else if (action === "grow" || effect === "growBar") {
            element.classList.add("show", "event-grow");
        }
        return {
            ok: true,
            waitForAnimationStart: duration > 0 && action !== "dim" && action !== "focus",
        };
    }

    // === 转场定义 ===
    var TRANSITIONS = {
        "push-left":  { exit: "slideExitLeft",    enter: "slideEnterRight" },
        "push-right": { exit: "slideExitRight",   enter: "slideEnterLeft" },
        "zoom":       { exit: "slideZoomOut",     enter: "slideZoomIn" },
        "dissolve":   { exit: "slideDissolveOut", enter: "slideDissolveIn" },
    };

    // === 工具函数 ===
    function getTransition(fromIndex, toIndex, direction) {
        var transitions = window.slideTransitions;
        if (!transitions || !transitions.length) return "push-left";

        var t = transitions[toIndex] || "push-left";

        if (direction === "backward") {
            if (t === "push-left") return "push-right";
            if (t === "push-right") return "push-left";
            if (t === "zoom") return "dissolve";
            if (t === "dissolve") return "zoom";
        }
        return t;
    }

    // === FLIP 工具 ===
    function captureFlipPositions(slide) {
        var positions = {};
        slide.querySelectorAll("[data-flip-id]").forEach(function (el) {
            var rect = el.getBoundingClientRect();
            positions[el.dataset.flipId] = { x: rect.left, y: rect.top, w: rect.width, h: rect.height };
        });
        return positions;
    }

    function animateFlip(slide, beforePositions, duration, easing, onlyFlipId) {
        var moved = {};
        var transitionDuration = isFinite(duration) && duration >= 0
            ? duration : DEFAULT_ANIMATION_DURATION;
        var transitionEasing = easing || "ease-out";
        slide.querySelectorAll("[data-flip-id]").forEach(function (el) {
            var id = el.dataset.flipId;
            if (onlyFlipId && id !== onlyFlipId) return;
            var before = beforePositions[id];
            if (!before) return;

            var after = el.getBoundingClientRect();
            var dx = before.x - after.left;
            var dy = before.y - after.top;

            if (Math.abs(dx) < 1 && Math.abs(dy) < 1) return;
            moved[id] = true;

            // Invert: 用 transform 将元素移回原位
            el.style.transform = "translate(" + dx + "px, " + dy + "px)";
            el.style.transition = "none";
            el.style.setProperty("--flip-duration", (transitionDuration / 1000) + "s");
            el.style.setProperty("--flip-easing", transitionEasing);
            // Commit the inverted position before the next frame so clearing
            // transform below creates a real CSS transition, not a same-frame
            // style replacement that the browser can coalesce.
            el.getBoundingClientRect();

            // Play: 下一帧移除 transform，触发 CSS transition
            requestAnimationFrame(function () {
                el.classList.add("flip-animating");
                el.style.transform = "";
                el.style.transition = "";

                setTimeout(function () {
                    el.classList.remove("flip-animating");
                    el.style.removeProperty("--flip-duration");
                    el.style.removeProperty("--flip-easing");
                }, transitionDuration);
            });
        });
        return moved;
    }

    // === Quiz card：手动/自动揭示答案解析 ===
    function revealQuizCard(card) {
        if (!card) return;
        card.querySelectorAll("[data-quiz-reveal]").forEach(function (el) {
            el.classList.add("show");
            el.setAttribute("aria-hidden", "false");
        });
        card.querySelectorAll("[data-quiz-action='reveal']").forEach(function (btn) {
            btn.style.display = "none";
        });
        card.setAttribute("data-quiz-revealed", "1");
    }

    function syncQuizCards(slide) {
        slide.querySelectorAll("[data-quiz-card]").forEach(function (card) {
            var revealed = false;
            card.querySelectorAll("[data-quiz-reveal]").forEach(function (el) {
                if (el.classList.contains("show")) {
                    revealed = true;
                    el.setAttribute("aria-hidden", "false");
                } else {
                    el.setAttribute("aria-hidden", "true");
                }
            });
            card.querySelectorAll("[data-quiz-action='reveal']").forEach(function (btn) {
                btn.style.display = revealed ? "none" : "";
            });
            if (revealed) {
                card.setAttribute("data-quiz-revealed", "1");
            } else {
                card.removeAttribute("data-quiz-revealed");
            }
        });
    }

    // === 退场 ===
    function exitSlide(index, transType) {
        var t = TRANSITIONS[transType] || TRANSITIONS["push-left"];
        var slide = slides[index];

        clearAnimationTimers();
        slide.classList.remove("active");
        slide.style.animationName = t.exit;
        slide.classList.add("transition-exit");

        slide.querySelectorAll(".anim").forEach(function (e) {
            e.classList.remove("show", "event-timed", "event-highlight", "event-pulse", "event-fade-out", "event-dim", "event-focus", "event-grow", "event-move");
            e.style.removeProperty("--anim-event-duration");
            e.style.removeProperty("--anim-event-easing");
            e.classList.remove("flip-animating");
            e.style.removeProperty("--flip-duration");
            e.style.removeProperty("--flip-easing");
        });

        setTimeout(function () {
            slide.classList.remove("transition-exit");
            slide.style.animationName = "";
        }, TRANSITION_DURATION);
    }

    // === 入场 ===
    function enterSlide(index, transType) {
        var t = TRANSITIONS[transType] || TRANSITIONS["push-left"];
        var slide = slides[index];

        slide.style.animationName = t.enter;
        slide.classList.add("transition-enter", "active");

        setTimeout(function () {
            slide.classList.remove("transition-enter");
            slide.style.animationName = "";
        }, TRANSITION_DURATION);

        triggerAnimations(index);
    }

    // === 带 FLIP 的 step 触发 ===
    function showStepWithFlip(
        slide, step, forceTimelineElements, duration, easing, onlyFlipId
    ) {
        // First: 记录当前 FLIP 元素位置
        var beforePositions = captureFlipPositions(slide);

        // 触发该 step 的元素
        slide.querySelectorAll(".anim").forEach(function (e) {
            var s = parseInt(e.dataset.step || "0", 10);
            if (s === step && (forceTimelineElements || !e.dataset.animId)) {
                e.classList.add("show");
            }
        });
        syncQuizCards(slide);

        // Last + Invert + Play
        var moved = animateFlip(slide, beforePositions, duration, easing, onlyFlipId);
        return onlyFlipId ? Boolean(moved[onlyFlipId]) : moved;
    }

    function scheduleStepAnimation(slide, slideIndex, step, delay) {
        var trace = scheduleTrace({
            event_id: "legacy-step-" + slideIndex + "-" + step,
            slide_id: "legacy-" + slideIndex,
            target: "data-step-" + step,
            selector: '[data-step="' + step + '"]',
            action: "show",
            effect: "legacy",
            start_ms: delay,
            duration_ms: DEFAULT_ANIMATION_DURATION,
            easing: "ease-out",
        });
        var timer = setTimeout(function () {
            showStepWithFlip(slide, step);
            finishTrace(trace, "executed", null);
        }, delay);
        pendingAnimationTimers.push({ timer: timer, trace: trace });
    }

    // === 动画触发核心逻辑 ===
    function triggerAnimations(index) {
        var slide = slides[index];
        var anims = slide.querySelectorAll(".anim");
        var timeline = window.slideTimelines && window.slideTimelines[index];
        var duration = (window.slideDurations && window.slideDurations[index]) || DEFAULT_SLIDE_DURATION;

        clearAnimationTimers();
        animationStartedAt = performance.now();
        // Keep visual-start diagnostics on the same clock origin as trace.actual_ms.
        window.__animationTraceStartedAt = animationStartedAt;

        if (timeline && timeline.length > 0) {
            // 精确时间轴模式
            // 先处理不在时间轴管控内且没有 data-step 的元素：立即触发
            var normalizedTimeline = timeline.map(normalizeTimelineEntry);
            anims.forEach(function (e) {
                var animId = e.dataset.animId;
                var step = parseInt(e.dataset.step || "0", 10);
                var scheduled = normalizedTimeline.some(function (entry) {
                    if (!entry.selector || !e.matches) return false;
                    try { return e.matches(entry.selector); } catch (_error) { return false; }
                });
                if ((!animId || !scheduled) && step === 0) {
                    e.classList.add("show");
                }
            });

            // 注册时间轴触发
            normalizedTimeline.forEach(function (entry, entryIndex) {
                var trace = scheduleTrace(entry);
                var startMs = Math.max(0, Number(entry.start_ms) || 0);
                var record = { timer: null, trace: trace, cleanup: null };
                record.timer = setTimeout(function () {
                    var beforePositions = captureFlipPositions(slide);
                    var targets;
                    try {
                        targets = slide.querySelectorAll(entry.selector);
                    } catch (error) {
                        completeAnimationRecord(record, "runtime_error", String(error));
                        return;
                    }
                    if (!targets.length) {
                        completeAnimationRecord(record, "target_missing", "No element matched " + entry.selector);
                        return;
                    }
                    if (entry.action === "move" && targets.length !== 1) {
                        completeAnimationRecord(
                            record,
                            "unsupported_action",
                            "unsupported_move:target must identify one element"
                        );
                        return;
                    }
                    if (entry.action === "move") {
                        record.cleanup = observeTransitionStart(trace, targets[0]);
                    } else if (eventNeedsAnimationStart(entry)) {
                        var visualTargets = animationTargetsForEvent(targets[0], entry);
                        if (visualTargets.length) {
                            record.cleanup = observeAnimationStart(trace, visualTargets);
                        }
                    }
                    var result = { ok: true };
                    targets.forEach(function (element) {
                        var applied = applyEvent(element, entry, slide);
                        if (!applied.ok) result = applied;
                        else result = Object.assign(result, applied);
                    });
                    if (!result.ok) {
                        completeAnimationRecord(record, "unsupported_action", result.error);
                        return;
                    }
                    syncQuizCards(slide);
                    if (entry.action !== "move") animateFlip(slide, beforePositions);
                    if ((result.waitForAnimationStart || result.waitForTransitionStart) && record.cleanup) {
                        return;
                    }
                    completeAnimationRecord(record, "executed", null);
                }, startMs);
                pendingAnimationTimers.push(record);
            });

            // data-step 元素按均分触发（带 FLIP）
            var maxStep = 0;
            anims.forEach(function (e) {
                var s = parseInt(e.dataset.step || "0", 10);
                if (s > maxStep) maxStep = s;
            });
            if (maxStep > 0) {
                var interval = duration / (maxStep + 1);
                for (var step = 1; step <= maxStep; step++) {
                    (function (s) {
                        scheduleStepAnimation(slide, index, s, interval * s);
                    })(step);
                }
            }
        } else {
            // Fallback 模式：data-step 均分 或 全部立即触发
            var maxStep = 0;
            anims.forEach(function (e) {
                var s = parseInt(e.dataset.step || "0", 10);
                if (s > maxStep) maxStep = s;
            });

            var interval = maxStep > 0 ? duration / (maxStep + 1) : 0;

            // Step 0: 立即触发
            anims.forEach(function (e) {
                var step = parseInt(e.dataset.step || "0", 10);
                if (step === 0) {
                    e.classList.add("show");
                }
            });
            syncQuizCards(slide);

            // Step 1+: 带 FLIP 延迟触发
            if (maxStep > 0) {
                for (var step = 1; step <= maxStep; step++) {
                    (function (s) {
                        scheduleStepAnimation(slide, index, s, interval * s);
                    })(step);
                }
            }
        }

        // 触发页面特定动画（如果已定义）
        if (typeof triggerSlideEffects === "function") {
            triggerSlideEffects(index);
        }
    }

    function exportAnimationTrace() {
        return window.animationTrace.map(function (entry) {
            return Object.assign({}, entry);
        });
    }

    function downloadAnimationTrace(filename) {
        var name = filename || "animation_trace.json";
        var blob = new Blob([JSON.stringify(exportAnimationTrace(), null, 2)], {
            type: "application/json",
        });
        var url = URL.createObjectURL(blob);
        var link = document.createElement("a");
        link.href = url;
        link.download = name;
        document.body.appendChild(link);
        link.click();
        link.remove();
        setTimeout(function () { URL.revokeObjectURL(url); }, 0);
        return name;
    }

    // === 页面切换 ===
    function go(index) {
        if (index < 0 || index >= total || index === current || transitioning) return;
        transitioning = true;

        var direction = index > current ? "forward" : "backward";
        var transType = getTransition(current, index, direction);

        exitSlide(current, transType);

        setTimeout(function () {
            current = index;
            enterSlide(current, transType);
            transitioning = false;
        }, TRANSITION_DURATION);
    }

    // === 初始化第一页 ===
    triggerAnimations(0);

    // === 键盘控制 ===
    document.addEventListener("keydown", function (e) {
        if (e.key === "ArrowRight" || e.key === "ArrowDown" || e.key === " ") {
            e.preventDefault();
            go(current + 1);
        } else if (e.key === "ArrowLeft" || e.key === "ArrowUp") {
            e.preventDefault();
            go(current - 1);
        }
    });

    // === 滚轮控制 ===
    var wheelLock = false;
    document.addEventListener("wheel", function (e) {
        if (wheelLock) return;
        wheelLock = true;
        setTimeout(function () {
            wheelLock = false;
        }, 600);
        e.deltaY > 0 ? go(current + 1) : go(current - 1);
    });

    // === 触摸滑动 ===
    var touchStartX = 0;
    var touchStartY = 0;
    document.addEventListener("touchstart", function (e) {
        touchStartX = e.changedTouches[0].screenX;
        touchStartY = e.changedTouches[0].screenY;
    });
    document.addEventListener("touchend", function (e) {
        var dx = e.changedTouches[0].screenX - touchStartX;
        var dy = e.changedTouches[0].screenY - touchStartY;
        if (Math.abs(dx) > Math.abs(dy)) {
            dx < 0 ? go(current + 1) : go(current - 1);
        } else {
            dy < 0 ? go(current + 1) : go(current - 1);
        }
    });

    document.addEventListener("click", function (e) {
        var target = e.target;
        if (!target || !target.closest) return;
        var button = target.closest("[data-quiz-action='reveal']");
        if (!button) return;
        e.preventDefault();
        var card = button.closest("[data-quiz-card]");
        revealQuizCard(card);
    });

    // === 暴露 API ===
    window.SlideController = {
        go: go,
        next: function () { go(current + 1); },
        prev: function () { go(current - 1); },
        current: function () { return current; },
        total: function () { return total; },
        slideDurations: window.slideDurations || [],
        slideTimelines: window.slideTimelines || [],
    };
    window.exportAnimationTrace = exportAnimationTrace;
    window.downloadAnimationTrace = downloadAnimationTrace;
})();

// === scale-to-fit：内容超出 content-box 时，对 .fit-scale 整体等比缩小塞进框 ===
// 保留丰富内容、不裁切（reveal.js/Beamer 的做法）。缩放打在不被动画的 .fit-scale
// 内层，粒子/装饰在其外，互不干扰。见 docs/research/adaptive-slide-layout.md §4.3。
(function () {
    var MIN_SCALE = 0.62;  // 缩放下限，过小则可读性差，宁可极端页轻微裁切
    function fitAll() {
        // 对每一页都做 scale-to-fit：模板页缩 .fit-scale；自由发挥页（无 .fit-scale）
        // 缩 slide 的单一根容器。两者都"溢出才缩、不溢出不动"，避免内容被 overflow:hidden 裁切。
        var slides = document.querySelectorAll(".slide");
        for (var i = 0; i < slides.length; i++) {
            var slide = slides[i];
            var fs = slide.querySelector(".fit-scale") || slide.firstElementChild;
            if (!fs) continue;
            fs.style.transform = "";               // 复位后测自然高度
            fs.style.transformOrigin = "center";
            var box = fs.parentElement;            // 模板=.t2v-content-box；自由发挥=.slide
            if (!box) continue;
            var cs = getComputedStyle(box);
            var pad = (parseFloat(cs.paddingTop) || 0) + (parseFloat(cs.paddingBottom) || 0);
            var avail = box.clientHeight - pad;    // 扣掉容器自身上下 padding
            var natural = fs.offsetHeight;         // offsetHeight 不受 transform 影响
            if (avail > 0 && natural > avail + 2) {
                var s = Math.max(MIN_SCALE, avail / natural);
                fs.style.transform = "scale(" + s.toFixed(4) + ")";
            }
        }
    }
    if (document.fonts && document.fonts.ready) {
        document.fonts.ready.then(function () { setTimeout(fitAll, 30); });
    }
    window.addEventListener("load", function () { setTimeout(fitAll, 80); });
    window.addEventListener("resize", fitAll);
    window.__fitAll = fitAll;  // 便于测量脚本手动触发
})();
